"""
HART-II rotor — HOVER, Cumulant + ALM + MLG.  Aeromechanics Workshop 2026, Task 3.

Shared config builder. Per-collective configs import `build_config()`:

    import sys, os
    sys.path.insert(0, os.path.dirname(__file__))
    from _hart2_hover_base import build_config
    config = build_config(collective_deg=8.0)        # production
    # config = build_config(collective_deg=8.0, smoke=True)   # CPU pipeline test

Task 3 deliverable: Figure of Merit vs C_T/sigma, generated by an OPEN-LOOP
collective sweep (3..16 deg).  FM = C_T^1.5 / (sqrt(2) * C_P).

=================================  PHYSICS  ===================================
HART-II rotor (all geometry from HART2_structural_property.xlsx "로터 모델링
데이터" block):
  - 4 blades, rotation CCW, R = 2.0 m, rectangular chord c = 0.121 m
  - linear twist -8 deg/R (washout), referenced to 0.75R
  - aerodynamic root cutout 0.44 m (r/R = 0.22)
  - airfoil NACA23012 (with tab) over the full span  -> NACA23012.C81 deck
  - RPM = 1041  (Omega = 109.0 rad/s, V_tip = 218.0 m/s)
  - solidity sigma = N c / (pi R) = 0.077
Atmosphere (workshop): rho = 1.2055 kg/m^3, T = 17.3 C
  -> a = 341.6 m/s, nu ~ 1.50e-5 m^2/s (Sutherland mu/rho); Re_0.75R ~ 1.3e6.

  *** PRECONE (coning) = 2.5 deg is NOT applied: the current ALM has no precone
      support (verified: no precone/coning in src/actuator/).  Effect on thrust
      is ~cos^2(2.5 deg) ~ 0.2% — negligible for a first FM curve.  Flagged for
      a possible future ALM extension. ***

==============================  WHY THESE CHOICES  ============================
Weak-compressibility & Mach.  The blade-relative tip Mach is 0.638, but in an
ALM the LBM grid never carries the section velocity — it resolves only the
low-Mach induced/wake field (M ~ 0.03-0.05 in hover).  The transonic blade
aerodynamics live entirely in the Mach-interpolated C81 lookup (airfoil_polar
method "c81").  See src/actuator/c81_loader.py.

Scaling.  CONVECTIVE (acoustic_scaling=False, u_max=0.1), NOT acoustic.
Acoustic scaling would map V_tip to u_max = V_tip/(c_s*sqrt3) = 0.368, which
exceeds the "u_max > 0.1 destabilises ALM forcing" threshold noted in prior ALM
work.  FM needs correct loads, not acoustic accuracy, so convective is the
robust choice.  The C81 Mach recovery (M = nu/(c*a)*Re) is scaling-invariant,
so loads stay correct either way.

Turbulence.  Re_0.75R ~ 1.3e6 -> WALE SGS on the resolved wake (Cumulant alone
is stable but adds numerical dissipation).  Toggle in `build_config`.
"""

import os

import numpy as np

# =============================================================================
# S1. PHYSICAL CONSTANTS (HART-II, confirmed)
# =============================================================================
R_PHYS      = 2.0                                  # [m] rotor radius
D_PHYS      = 2.0 * R_PHYS                          # [m] diameter = 4.0
CHORD_PHYS  = 0.121                                 # [m] constant chord
N_BLADES    = 4
ROOT_CUT_R  = 0.44                                  # [m] aero root cutout
ROOT_CUT_RR = ROOT_CUT_R / R_PHYS                   # = 0.22
TWIST_RATE  = -8.0                                  # [deg/R] linear washout
TWIST_REF   = 0.75                                  # collective defined @ 0.75R
PRECONE_DEG = 2.5                                   # [deg] NOT applied (see header)

RPM         = 1041
OMEGA_PHYS  = RPM * 2.0 * np.pi / 60.0              # [rad/s] = 109.0
TIP_SPEED   = OMEGA_PHYS * R_PHYS                   # [m/s]   = 218.0
SIGMA       = N_BLADES * CHORD_PHYS / (np.pi * R_PHYS)   # solidity = 0.077

RHO_PHYS    = 1.2055                                # [kg/m^3]
C_S_PHYS    = 341.6                                 # [m/s] sound speed @ 17.3 C
NU_PHYS     = 1.50e-5                               # [m^2/s] mu_Sutherland/rho

RE_75       = 0.75 * TIP_SPEED * CHORD_PHYS / NU_PHYS    # ~1.32e6
M_TIP       = TIP_SPEED / C_S_PHYS                       # 0.638

# C81 deck. Primary copy lives in data/airfoils/ (the tree that IS deployed
# to the cluster alongside src/ and configs/ — aeromechanics_workshop/ is
