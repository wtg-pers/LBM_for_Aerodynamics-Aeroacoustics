# S4. STANDALONE — parameter + memory summary (per preset)
# =============================================================================
def _estimate_cells(cfg):
    """Total MLG node count via OverlapManager (exact), + approx GB."""
    import sys
    sys.path.insert(0, _REPO)
    from src.grid.overlap_manager import OverlapManager, IndexBox
    from src.grid.level_scaling import LevelScaler
    g, m = cfg["grid"], cfg["mlg"]
    Nx, Ny, Nz = g["Nx"], g["Ny"], g["Nz"]
    scaler = LevelScaler(tau_0=0.503, num_levels=m["num_levels"])
    mgr = OverlapManager()
    coarse = (Nx, Ny, Nz); origins = [(0, 0, 0)]; spac = [(1, 1, 1)]
    tot = Nx * Ny * Nz; per = [tot]
    for k in range(1, m["num_levels"]):
        rc = m["levels"][k]["region"]; po, pd = origins[k - 1], spac[k - 1]
        fr = IndexBox(round((rc["x_min"] - po[0]) / pd[0]), round((rc["x_max"] - po[0]) / pd[0]),
                      round((rc["y_min"] - po[1]) / pd[1]), round((rc["y_max"] - po[1]) / pd[1]),
                      round((rc["z_min"] - po[2]) / pd[2]), round((rc["z_max"] - po[2]) / pd[2]))
        reg = mgr.add_level_pair(coarse, fr, m["overlap_width"])
        fdc = reg.fine_domain_coarse; lu = scaler.get_level_units(k)
        origins.append((po[0] + fdc.x_start * pd[0], po[1] + fdc.y_start * pd[1],
                        po[2] + fdc.z_start * pd[2]))
        spac.append((lu.dx,) * 3); fs = reg.fine_shape
        n = fs[0] * fs[1] * fs[2]; tot += n; per.append(n); coarse = fs
    return tot, per


